import { expect, test, pixelsAt, colourDistance } from "./fixture";
import { openRoll, sessionNotes, twoChannels, boxSelect, local, nextFrame, canvas } from "./rollHelpers";
import { humanize } from "../src/roll/transforms";
const notes = [60, 64, 67].map((key, i) => ({ id: i + 1, channel: 1, tick: 480, key, length: 240, velocity: Math.fround(0.8), slide: false }));
test.use({ seed: { project: twoChannels(notes, { key: { root: 0, scale: "major" } }) } });
test("feel controls apply actual selected notes with whole-operation history", async ({ app, mock }, info) => {
  await openRoll(app);
  await boxSelect(app, 10, 70, 1500, 58);
  const before = await sessionNotes(mock);
  await nextFrame(app);
  const point = await local(app, 510, 67);
  const [beforePixel] = await pixelsAt(app, canvas(app), [point]);
  await app.getByText("Feel", { exact: true }).click();
  const spread = app.getByRole("slider", { name: "Strum spread", exact: true });
  await spread.press("End");
  await app.getByRole("button", { name: "Strum up", exact: true }).click();
  await expect.poll(() => sessionNotes(mock)).toEqual([[1,480,240,60],[1,600,240,64],[1,720,240,67]]);
  await nextFrame(app);
  const [afterPixel] = await pixelsAt(app, canvas(app), [point]);
  expect(colourDistance(beforePixel, afterPixel)).toBeGreaterThan(50);
  await app.keyboard.press("ControlOrMeta+KeyZ");
  await expect.poll(() => sessionNotes(mock)).toEqual(before);
  await app.keyboard.press("ControlOrMeta+Shift+KeyZ");
  await expect.poll(() => sessionNotes(mock)).toEqual([[1,480,240,60],[1,600,240,64],[1,720,240,67]]);
  await app.keyboard.press("ControlOrMeta+KeyZ");
  await expect.poll(() => sessionNotes(mock)).toEqual(before);
  await spread.dblclick();
  await expect(spread).toHaveAttribute("aria-valuenow", "30");
  const timing = app.getByRole("slider", { name: "Humanize timing", exact: true });
  const velocity = app.getByRole("slider", { name: "Humanize velocity", exact: true });
  await timing.press("End"); await velocity.press("Home");
  await app.getByRole("button", { name: "Humanize", exact: true }).click();
  const expected = humanize(notes, 120, 0, 1);
  await expect.poll(() => sessionNotes(mock)).toEqual(expected.map(n => [n.channel,n.tick,n.length,n.key]));
  const edited = (await mock.calls("notes_edit")).at(-1)!.args.edit as { update: typeof notes };
  expect(edited.update.map(n => n.velocity)).toEqual([Math.fround(0.8),Math.fround(0.8),Math.fround(0.8)]);
  await app.keyboard.press("ControlOrMeta+KeyZ");
  await expect.poll(() => sessionNotes(mock)).toEqual(before);
  await timing.press("Home"); await velocity.press("End");
  await app.getByRole("button", { name: "Humanize", exact: true }).click();
  const actual = (await mock.calls("notes_edit")).at(-1)!.args.edit as { update: typeof notes };
  expect(actual.update).toEqual(humanize(notes, 0, 1, 2));
  await app.screenshot({ path: info.outputPath("feel.png") });
});
test("cancel and reset reuse knob ownership; key cues retain preview release", async ({ app, mock }) => {
  await openRoll(app);
  await app.getByText("Feel", { exact: true }).click();
  const knob = app.getByRole("slider", { name: "Humanize timing", exact: true });
  const b = (await knob.boundingBox())!;
  await app.mouse.move(b.x + b.width/2, b.y + 20); await app.mouse.down();
  await app.mouse.move(b.x + b.width/2, b.y - 40, { steps: 4 });
  await app.keyboard.press("Escape"); await app.mouse.up();
  await expect(knob).toHaveAttribute("aria-valuenow", "20");
  await knob.press("End"); await knob.dblclick();
  await expect(knob).toHaveAttribute("aria-valuenow", "20");
  const root = app.locator('.roll-key[data-key="60"]');
  const other = app.locator('.roll-key[data-key="61"]');
  expect(await root.evaluate(el => getComputedStyle(el).boxShadow)).not.toEqual(await other.evaluate(el => getComputedStyle(el).boxShadow));
  const keys = app.getByRole("group", { name: "Piano keys" });
  const p = await local(app, 0, 60); const kb = (await keys.boundingBox())!;
  await app.mouse.move(kb.x+15, kb.y+p.y); await app.mouse.down();
  await app.mouse.up();
  await expect.poll(async () => (await mock.calls("channel_note")).filter(c => c.args.on === false).length).toBe(1);
  await expect(app.locator(".roll-key.held")).toHaveCount(0);
});
